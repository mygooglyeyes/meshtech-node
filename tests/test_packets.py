def _advert_payload(prefix=0x42, ts=1234567890, flags=0x90,
                    lat=41.7, lon=-111.8, name=b"LoganPeak"):
    payload = bytes([prefix]) + b"\x11" * 31            # 32B pubkey
    payload += ts.to_bytes(4, "little")
    payload += b"\x22" * 64                             # signature
    payload += bytes([flags])
    if flags & 0x10:
        payload += int(lat * 1e6).to_bytes(4, "little", signed=True)
        payload += int(lon * 1e6).to_bytes(4, "little", signed=True)
    if flags & 0x80:
        payload += name
    return payload


def test_parse_advert_full():
    info = parse_advert(_advert_payload())
    assert info is not None
    assert info.prefix == 0x42
    assert info.origin_ts == 1234567890.0
    assert info.flags == 0x90
    assert abs(info.lat - 41.7) < 0.001
    assert abs(info.lon - (-111.8)) < 0.001
    assert info.name == "LoganPeak"
    assert info.node_class == 0                          # flags & 0x0F = 0


def test_parse_advert_no_location():
    info = parse_advert(_advert_payload(flags=0x80))
    assert info.lat is None and info.lon is None
    assert info.name == "LoganPeak"


def test_parse_advert_short_payload_is_none():
    assert parse_advert(b"\x42" + b"\x00" * 50) is None


def test_parse_advert_truncated_location_is_honest():
    # flags say location, bytes missing -> flags-only result, no crash
    payload = bytes([0x42]) + b"\x11" * 31 + (1234567890).to_bytes(4, "little") \
        + b"\x22" * 64 + bytes([0x90]) + b"\x01\x02"
    info = parse_advert(payload)
    assert info is not None
    assert info.lat is None and info.lon is None
