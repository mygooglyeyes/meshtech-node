def _build_frame(payload_type: int, route: int, payload: bytes,
                 transport_codes=None, hops: int = 0, hash_size: int = 1,
                 path: bytes = b"") -> bytes:
    header = (0 << 6) | (payload_type << 2) | route
    out = bytes([header])
    if route in (0, 3):
        tc = transport_codes or (0x1122, 0x3344)
        out += tc[0].to_bytes(2, "little") + tc[1].to_bytes(2, "little")
    path_len_byte = ((hash_size - 1) << 6) | (hops & 0x3F)
    out += bytes([path_len_byte]) + path
    return out + payload


def test_split_frame_transport_flood_with_codes():
    # route 0 = TRANSPORT_FLOOD per reference constants.py:16 - carries codes
    frame = split_frame(_build_frame(PAYLOAD_TYPE_GRP_DATA, 0, b"\x01\x02"))
    assert frame is not None
    assert frame.payload_type == PAYLOAD_TYPE_GRP_DATA
    assert frame.route == 0
    assert frame.transport_codes == (0x1122, 0x3344)
    assert frame.hops == 0


def test_split_frame_direct_no_transport_codes():
    frame = split_frame(_build_frame(0x02, 2, b"\x01"))
    assert frame is not None
    assert frame.transport_codes is None
    assert frame.hops == 0


def test_split_frame_path_hops_preserved():
    path = bytes([0xAA, 0xBB, 0xCC, 0xDD])          # 2 hops x 2-byte hashes
    frame = split_frame(_build_frame(0x05, 0, b"\x01", hops=2,
                                     hash_size=2, path=path))
    assert frame is not None
    assert frame.hops == 2
    assert frame.hash_size == 2
    assert frame.path == path
    assert frame.transport_codes == (0x1122, 0x3344)


def test_split_frame_rejects_truncated_path():
    bad = _build_frame(0x05, 0, b"\x01", hops=3, hash_size=1,
                       path=b"\xAA")                # claims 3, carries 1
    assert split_frame(bad) is None


def test_split_frame_rejects_bad_hash_size():
    # flood-header frame whose path_len byte encodes hash_size 4
    bad = bytes([0x14]) + b"\x00" * 4 + b"\xC0" + b"\x01"
    assert split_frame(bad) is None


