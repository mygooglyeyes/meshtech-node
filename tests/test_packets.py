def test_dedupe_scripted_counts():
    """The BENCH-CHECKLIST dedupe script: N=3 distinct, M=2 dup each,
    K=0 drops - health numbers must match the script exactly."""
    dedupe = FloodDedupe(now=1000.0)
    distinct = [b"\x01", b"\x02", b"\x03"]
    dup_count = 2
    seen_first_time = 0
    seen_duplicate = 0
    for payload in distinct:
        for _ in range(dup_count + 1):
            if dedupe.is_duplicate(PAYLOAD_TYPE_GRP_DATA, payload):
                seen_duplicate += 1
            else:
                seen_first_time += 1
    assert seen_first_time == 3
    assert seen_duplicate == 6
    # window expiry: at t=1046 (46 s later) the same payload is new again
    dedupe2 = FloodDedupe(now=1000.0)
    assert dedupe2.is_duplicate(PAYLOAD_TYPE_GRP_DATA, b"\x09") is False
    assert dedupe2.is_duplicate(PAYLOAD_TYPE_GRP_DATA, b"\x09") is True
    dedupe3 = FloodDedupe(now=1000.0)
    dedupe3.is_duplicate(PAYLOAD_TYPE_GRP_DATA, b"\x09")
    dedupe3._now = lambda: 1000.0 + FLOOD_DEDUPE_WINDOW_S + 1
    assert dedupe3.is_duplicate(PAYLOAD_TYPE_GRP_DATA, b"\x09") is False


def test_own_tx_window_longer():
    dedupe = FloodDedupe(now=1000.0)
    dedupe.mark_own_tx(PAYLOAD_TYPE_GRP_DATA, b"\xAB")
    assert dedupe.is_duplicate(PAYLOAD_TYPE_GRP_DATA, b"\xAB") is True
    dedupe._now = lambda: 1000.0 + 121.0
    assert dedupe.is_duplicate(PAYLOAD_TYPE_GRP_DATA, b"\xAB") is False


