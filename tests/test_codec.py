# Regenerate with: python tools/gen_golden.py (writes
# tests/golden_vectors.json; keep in sync with scope-app codec.test.ts).
# The test READS the json - one source of truth, no hand-copied drift.

import json as _json
from pathlib import Path as _Path

GOLDEN = _json.loads((_Path(__file__).parent / "golden_vectors.json")
                     .read_text(encoding="utf-8"))


@pytest.mark.parametrize("name", sorted(GOLDEN.keys()))
def test_golden_vectors(name):
    """Decode the pinned vectors and re-encode; bytes must match."""
    raw = bytes.fromhex(GOLDEN[name])
    obj = codec.decode_any(raw)
    if name == "pulse":
        assert codec.encode_pulse(obj) == raw
    elif name == "sect_sum":
        assert codec.encode_sect_sum(obj) == raw
    elif name == "route":
        assert codec.encode_route(obj) == raw
    elif name == "layout":
        assert codec.encode_layout(obj) == raw
    elif name == "intro":
        intro = codec.Intro(seq=obj.seq, origin=obj.origin,
                            entries=obj.entries,
                            center_lat=0.0, center_lon=0.0, span_m=40000.0)
        assert codec.encode_intro(intro) == raw
    elif name == "refresh":
        assert codec.encode_refresh_req(obj) == raw
