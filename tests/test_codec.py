# ---------------------------------------------------------------- PULSE

def test_pulse_roundtrip():
    p = codec.Pulse(seq=7, uptime_min=1234, rx_per_hour=5321,
                    feed_airtime_s_per_h=9, active_total=40, origin=0xB17E,
                    section_counts=[3, 5, 8, 2, 0, 1, 4, 6, 3])
    raw = codec.encode_pulse(p)
    assert len(raw) <= codec.TARGET_PAYLOAD
    out = codec.decode_pulse(raw[3:])
    assert out.seq == 7
    assert out.origin == 0xB17E
    assert out.uptime_min == 1234
    assert out.rx_per_hour == 5321
    assert out.feed_airtime_s_per_h == 9
    assert out.active_total == 40
    assert out.section_counts == [3, 5, 8, 2, 0, 1, 4, 6, 3]


