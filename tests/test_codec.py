# ---------------------------------------------------------------- INTRO

def test_intro_roundtrip_with_positions():
    intro = codec.Intro(
        seq=5, origin=0xB17E, center_lat=37.0, center_lon=-122.0,
        span_m=40000.0,
        entries=[
            codec.IntroEntry(prefix=0x11, name="Hilltop", lat=37.1,
                             lon=-122.1),
            codec.IntroEntry(prefix=0x22, name="Relay2"),
            codec.IntroEntry(prefix=0x33),
        ])
    raw = codec.encode_intro(intro)
    out = codec.decode_intro(raw[3:], center_lat=37.0, center_lon=-122.0,
                             span_m=40000.0)
    assert out.seq == 5
    assert out.origin == 0xB17E
    assert [e.prefix for e in out.entries] == [0x11, 0x22, 0x33]
    assert out.entries[0].name == "Hilltop"
    # position reconstructs within delta resolution (~1.2 m at 40 km span)
    assert abs(out.entries[0].lat - 37.1) < 0.002
    assert abs(out.entries[0].lon - -122.1) < 0.004
    assert out.entries[1].lat is None
    assert out.entries[2].name is None


