# ---------------------------------------------------------------- REFRESH_REQ

def test_refresh_req_roundtrip():
    r = codec.RefreshReq(seq=11, kind=codec.REFRESH_KIND_ROUTE,
                         target=0xBEEF, nonce=0x1234,
                         origin=0x0042, host=0xB17E)
    raw = codec.encode_refresh_req(r)
    out = codec.decode_any(raw)   # full plaintext incl. data_type framing
    assert out.kind == codec.REFRESH_KIND_ROUTE
    assert out.target == 0xBEEF
    assert out.nonce == 0x1234
    assert out.origin == 0x0042   # client's own id
    assert out.host == 0xB17E     # preferred host, 0 = owner decides


def test_refresh_req_defaults_are_owner_decides():
    r = codec.RefreshReq(seq=1, kind=codec.REFRESH_KIND_SECTION,
                         target=4, nonce=5)
    out = codec.decode_refresh_req(codec.encode_refresh_req(r)[3:])
    assert out.host == codec.REFRESH_HOST_ANY
    assert out.origin == 0


def test_refresh_req_rejects_bad_kind():
    with pytest.raises(codec.CodecError):
        codec.encode_refresh_req(codec.RefreshReq(seq=0, kind=9, target=0,
                                                  nonce=0))


# ---------------------------------------------------------------- v1 compat

def test_intro_node_class_roundtrip():
    """Class rides the flags byte (bits 2-3): repeater + companion +
    unknown all survive a roundtrip, and positions/names are unaffected."""
    intro = codec.Intro(
        seq=5, origin=0xB17E, center_lat=37.0, center_lon=-122.0,
        span_m=40000.0,
        entries=[
            codec.IntroEntry(prefix=0x11, name="Hilltop", lat=37.1,
                             lon=-122.1, node_class=codec.NODE_CLASS_REPEATER),
            codec.IntroEntry(prefix=0x22, name="Phone",
                             node_class=codec.NODE_CLASS_COMPANION),
            codec.IntroEntry(prefix=0x33),   # unknown class, no name
        ])
    raw = codec.encode_intro(intro)
    out = codec.decode_intro(raw[3:], center_lat=37.0, center_lon=-122.0,
                             span_m=40000.0)
    assert out.entries[0].node_class == codec.NODE_CLASS_REPEATER
    assert out.entries[1].node_class == codec.NODE_CLASS_COMPANION
    assert out.entries[2].node_class == codec.NODE_CLASS_UNKNOWN
    assert out.entries[0].name == "Hilltop"
    assert abs(out.entries[0].lat - 37.1) < 0.002


def test_intro_node_class_clamps_out_of_range():
    """An over-wide class value clamps into 2 bits, never corrupts
    the name/position flags."""
    entry = codec.IntroEntry(prefix=1, name="X", lat=1.0, lon=1.0,
                             node_class=0x07)
    assert entry.flags & 0x03 == 0x03          # name + position intact
    assert (entry.flags >> 2) & 0x03 == 0x03   # class clamped to reserved


def test_v1_intro_still_decodes_class_unknown():
    """A v1-era intro (flags without class bits) decodes with class 0."""
    v1 = bytes.fromhex(
        "04531a0102000211030748696c6c746f7024002400220105416c696365")
    out = codec.decode_any(v1)
    assert all(e.node_class == 0 for e in out.entries)


def test_v1_packets_still_decode():
    """A v1 (3-byte header) packet decodes with origin 0 - old captures
    and old firmware companions must not break."""
    v1 = bytes.fromhex(
        "0553130103000344d61200a01ce9ff409c0464656d6f")
    layout = codec.decode_any(v1)
    assert layout.origin == 0
    assert layout.grid == 3
    assert layout.name == "demo"


