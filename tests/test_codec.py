def test_payload_budget_respected():
    """Every encodable packet type stays inside the 120-byte target
    with realistic content."""
    pulse = codec.encode_pulse(codec.Pulse(
        seq=0, uptime_min=0, rx_per_hour=0xFFFF, feed_airtime_s_per_h=99,
        active_total=0xFFFF, origin=0xB17E, section_counts=[9] * 25))
    assert len(pulse) <= codec.TARGET_PAYLOAD
    intro = codec.encode_intro(codec.Intro(
        seq=0, origin=0xB17E,
        entries=[codec.IntroEntry(prefix=i, name="N" * 20,
                                  lat=1.0, lon=1.0)
                 for i in range(4)]))
    assert len(intro) <= codec.TARGET_PAYLOAD
    route = codec.encode_route(codec.Route(
        seq=0, section_id=1, route_id=0, packet_count=0, delay_med_s=0,
        last_heard_min=0, origin=0xB17E, prefixes=list(range(8))))
    assert len(route) <= codec.TARGET_PAYLOAD


def test_peek_and_decode_any():
    raw = codec.encode_layout(codec.Layout(seq=1, grid=3,
                                           center_lat=1.0, center_lon=2.0,
                                           span_m=1000, origin=0xB17E,
                                           name="x"))
    assert codec.peek_data_type(raw) == codec.TYPE_LAYOUT
    obj = codec.decode_any(raw)
    assert isinstance(obj, codec.Layout)


def test_unknown_type_raises():
    with pytest.raises(codec.CodecError):
        codec.decode_any(b"\x99\x53\x03\x01\x00\x00")


def test_truncated_payloads_raise_not_crash():
    good = codec.encode_pulse(codec.Pulse(seq=1, uptime_min=2, rx_per_hour=3,
                                          feed_airtime_s_per_h=4,
                                          active_total=5, origin=0xB17E,
                                          section_counts=[1, 2, 3]))
    for cut in range(0, len(good)):
        with pytest.raises(codec.CodecError):
            codec.decode_pulse(good[3:cut])


