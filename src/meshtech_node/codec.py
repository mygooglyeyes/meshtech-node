# PULSE (0x5301)
# --------------------------------------------------------------------------

@dataclass
class Pulse:
    seq: int
    uptime_min: int
    rx_per_hour: int
    feed_airtime_s_per_h: int
    active_total: int
    origin: int = 0
    section_counts: List[int] = field(default_factory=list)


def encode_pulse(p: Pulse) -> bytes:
    if len(p.section_counts) > 255:
        raise CodecError("too many sections")
    body = pack_header(p.seq, p.origin)
    body += struct.pack(
        "<HHHHB",
        _u16(p.uptime_min, "uptime_min"),
        _u16(p.rx_per_hour, "rx_per_hour"),
        _u16(p.feed_airtime_s_per_h, "feed_airtime_s_per_h"),
        _u16(p.active_total, "active_total"),
        len(p.section_counts),
    )
    for count in p.section_counts:
        body += struct.pack("<B", _u8(count, "section count"))
    return data_type_bytes(TYPE_PULSE, body)


def decode_pulse(payload: bytes) -> Pulse:
    header, off = unpack_header(payload)
    if len(payload) < off + 9:
        raise CodecError("PULSE too short")
    uptime, rx, air, total, n = struct.unpack_from("<HHHHB", payload, off)
    off += 9
    if len(payload) - off < n:
        raise CodecError("PULSE section counts truncated")
    counts = [payload[off + i] for i in range(n)]
    return Pulse(seq=header.seq, uptime_min=uptime, rx_per_hour=rx,
                 feed_airtime_s_per_h=air, active_total=total,
                 origin=header.origin, section_counts=counts)


# --------------------------------------------------------------------------
# SECT_SUM (0x5302)
# --------------------------------------------------------------------------

@dataclass
class SectSum:
    seq: int
    section_id: int
    active_nodes: int
    packet_count: int
    delay_p50_s: int
    delay_p90_s: int
    origin: int = 0
    route_stubs: List[int] = field(default_factory=list)  # route_ids


def _check_section_id(value: int, where: str) -> int:
    """Wire section ids are 1-BASED (v1.2): 1..255 valid on the byte.

    0 is reserved (whole-area marker in REFRESH_REQ targets); a
    SECT_SUM/ROUTE carrying 0 is malformed - reject at the boundary
    instead of drawing a phantom NW square."""
    value = _u8(value, where)
    if value == REFRESH_WHOLE_AREA:
        raise CodecError(f"{where}: 0 is reserved (whole-area)")
    return value


def encode_sect_sum(s: SectSum) -> bytes:
    if len(s.route_stubs) > 255:
        raise CodecError("too many route stubs")
    body = pack_header(s.seq, s.origin)
    body += struct.pack(
        "<BBHHHBB",
        _check_section_id(s.section_id, "section_id"),
        _u8(s.active_nodes, "active_nodes"),
        _u16(s.packet_count, "packet_count"),
        _u16(s.delay_p50_s, "delay_p50_s"),
        _u16(s.delay_p90_s, "delay_p90_s"),
        0,  # reserved byte keeps the struct readable
        len(s.route_stubs),
    )
    for rid in s.route_stubs:
        body += struct.pack("<H", _u16(rid, "route_id"))
    return data_type_bytes(TYPE_SECT_SUM, body)


def decode_sect_sum(payload: bytes) -> SectSum:
    header, off = unpack_header(payload)
    if len(payload) < off + 10:
        raise CodecError("SECT_SUM too short")
    section_id, active, packets, p50, p90, _reserved, n = \
        struct.unpack_from("<BBHHHBB", payload, off)
    off += 10
    _check_section_id(section_id, "decoded section_id")
    if len(payload) < off + 2 * n:
        raise CodecError("SECT_SUM stubs truncated")
    stubs = [struct.unpack_from("<H", payload, off + 2 * i)[0]
             for i in range(n)]
    return SectSum(seq=header.seq, section_id=section_id,
                   active_nodes=active, packet_count=packets,
                   delay_p50_s=p50, delay_p90_s=p90, origin=header.origin,
                   route_stubs=stubs)


