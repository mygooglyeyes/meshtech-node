# ROUTE (0x5303)
# --------------------------------------------------------------------------

@dataclass
class Route:
    seq: int
    section_id: int
    route_id: int
    packet_count: int
    delay_med_s: int
    last_heard_min: int
    origin: int = 0
    prefixes: List[int] = field(default_factory=list)  # 1 byte each


def encode_route(r: Route) -> bytes:
    if len(r.prefixes) > 255:
        raise CodecError("too many prefixes")
    body = pack_header(r.seq, r.origin)
    body += struct.pack(
        "<BHHHHB",
        _check_section_id(r.section_id, "section_id"),
        _u16(r.route_id, "route_id"),
        _u16(r.packet_count, "packet_count"),
        _u16(r.delay_med_s, "delay_med_s"),
        _u16(r.last_heard_min, "last_heard_min"),
        len(r.prefixes),
    )
    for pfx in r.prefixes:
        body += struct.pack("<B", _u8(pfx, "prefix"))
    return data_type_bytes(TYPE_ROUTE, body)


def decode_route(payload: bytes) -> Route:
    header, off = unpack_header(payload)
    if len(payload) < off + 10:
        raise CodecError("ROUTE too short")
    section_id, route_id, packets, delay, last, n = \
        struct.unpack_from("<BHHHHB", payload, off)
    _check_section_id(section_id, "decoded section_id")
    off += 10
    if len(payload) < off + n:
        raise CodecError("ROUTE prefixes truncated")
    prefixes = [payload[off + i] for i in range(n)]
    return Route(seq=header.seq, section_id=section_id, route_id=route_id,
                 packet_count=packets, delay_med_s=delay,
                 last_heard_min=last, origin=header.origin,
                 prefixes=prefixes)


# --------------------------------------------------------------------------
# INTRO (0x5304)
# --------------------------------------------------------------------------

@dataclass
class IntroEntry:
    prefix: int
    name: Optional[str] = None
    lat: Optional[float] = None
    lon: Optional[float] = None
    node_class: int = NODE_CLASS_UNKNOWN

    @property
    def flags(self) -> int:
        flags = 0
        if self.name:
            flags |= 0x01
        if self.lat is not None and self.lon is not None:
            flags |= 0x02
        flags |= (self.node_class & NODE_CLASS_MASK) << NODE_CLASS_SHIFT
        return flags


@dataclass
class Intro:
    seq: int = 0
    origin: int = 0
    entries: List[IntroEntry] = field(default_factory=list)
    # Deltas are relative to the LAYOUT centre/span (set by the builder);
    # the codec needs them to encode, and returns them on decode.
    center_lat: float = 0.0
    center_lon: float = 0.0
    span_m: float = 40000.0
    # THE SPAN RIDES ON THE WIRE (2026-09-23, Brett's "new set of offset
    # dots on every connect"): INTRO positions are deltas measured
    # against a map span, but v1.0-1.4 carried no span - the client
    # GUESSED it from whatever LAYOUT it held, and a mismatch (a sized
    # window, a replayed LAYOUT at connect) scaled every delta wrong.
    # v1.5: 2 LE meters. encode writes it; decode uses it as the truth
    # (opts.spanM, when given, is only cross-checked). 2.783 m of
    # position quantization at 60 km - far below GPS noise.
    wire_span_m: Optional[int] = None


def _position_deltas(intro: Intro, lat: float, lon: float) -> Tuple[int, int]:
    span_deg = intro.span_m / 111320.0
    dlat = round((lat - intro.center_lat) / span_deg * 32767)
    dlon = round((lon - intro.center_lon) / span_deg * 32767)
    # NEVER PIN (Brett's hard rule 2, 2026-09-26): a delta past the
    # end of the ruler used to be clamped to its end - a FABRICATED
    # position (the pile-of-dots ring the 60 km view exposed). A
    # ruler that cannot reach a node is a builder bug, and the honest
    # answer is the loud one: refuse to mint the packet at all.
    if not -32767 <= dlat <= 32767 or not -32767 <= dlon <= 32767:
        raise CodecError(
            f"position ({lat}, {lon}) falls outside the intro ruler "
            f"({intro.span_m} m) - widen the ruler; "
            f"never pin a fake position")
    return dlat, dlon


def _position_from_deltas(intro: Intro, dlat: int, dlon: int) -> Tuple[float, float]:
    span_deg = intro.span_m / 111320.0
    return (intro.center_lat + dlat / 32767.0 * span_deg,
            intro.center_lon + dlon / 32767.0 * span_deg)


def encode_intro(i: Intro) -> bytes:
    if len(i.entries) > 255:
        raise CodecError("too many intro entries")
    span_wire = round(i.span_m)
    if not 0 < span_wire <= 0xFFFFFF:
        raise CodecError(f"intro span_m out of wire range: {i.span_m}")
    body = pack_header(i.seq, i.origin, version=PROTO_VERSION_INTRO)
    # v1.6 (Brett, 2026-09-26): the span field IS THE RULER and grew
    # to 3 LE bytes - the old 2-byte meters field capped at 65.5 km
    # and pinned every farther node at its end. Old decoders refuse
    # v1.6 packets loudly (their version check), never silently wrong.
    body += span_wire.to_bytes(3, "little")
    body += struct.pack("<B", len(i.entries))
    for entry in i.entries:
        name_bytes = (entry.name or "").encode("utf-8")[:MAX_NAME]
        body += struct.pack("<BB", _u8(entry.prefix, "prefix"),
                            entry.flags)
        body += struct.pack("<B", len(name_bytes))
        if name_bytes:
            body += name_bytes
        if entry.flags & 0x02:
            dlat, dlon = _position_deltas(i, entry.lat, entry.lon)
            body += struct.pack("<hh", dlat, dlon)
    return data_type_bytes(TYPE_INTRO, body)


def decode_intro(payload: bytes, *, center_lat: float = 0.0,
                 center_lon: float = 0.0,
                 span_m: Optional[float] = None) -> Intro:
    """Decode INTRO. Positions are reconstructed from deltas against
    the span THE PACKET CARRIES (since v1.5) and the LAYOUT center the
    client already has (pass it here).

    span_m: a fallback ONLY for pre-v1.5 packets (nothing on the
    wire to trust). v1.6 (2026-09-26): the span is THE RULER - the
    scale measured to REACH every node in the packet (3 LE meters),
    so no position is ever pinned at a window edge and none is ever
    dropped. The old span cross-check is gone: the packet's span is
    the truth, and comparing a ruler to a LAYOUT window is noise."""
    header, off = unpack_header(payload)
    if header.version >= 0x06:
        # v1.6: the ruler, 3 LE meters.
        if len(payload) < off + 3:
            raise CodecError("INTRO too short for span field")
        wire_span = int.from_bytes(payload[off:off + 3], "little")
        off += 3
        if wire_span <= 0:
            raise CodecError(f"INTRO span must be positive, got {wire_span}")
    elif header.version >= 0x05:
        # v1.5: 2 LE meters (packets still in flight from an old host).
        if len(payload) < off + 2:
            raise CodecError("INTRO too short for span field")
        wire_span = struct.unpack_from("<H", payload, off)[0]
        off += 2
        if wire_span <= 0:
            raise CodecError(f"INTRO span must be positive, got {wire_span}")
    else:
        # v1.0-1.4 packets carry NO span (the old guess-field): fall
        # back to the caller's span, or the era's 40 km assumption -
        # exactly the behavior that produced Brett's offset-dots bug,
        # kept ONLY for packets still in flight from a pre-v1.5 host.
        wire_span = round(span_m) if span_m is not None else 40000
        if wire_span <= 0:
            raise CodecError(f"INTRO span must be positive, got {wire_span}")
    count = payload[off]
    off += 1
    intro = Intro(seq=header.seq, origin=header.origin,
                  center_lat=center_lat, center_lon=center_lon,
                  span_m=float(wire_span),
                  wire_span_m=wire_span if header.version >= 0x05 else None)
    for _ in range(count):
        if len(payload) < off + 3:
            raise CodecError("INTRO entry truncated")
        prefix, flags = struct.unpack_from("<BB", payload, off)
        name_len = payload[off + 2]
        off += 3
        node_class = (flags >> NODE_CLASS_SHIFT) & NODE_CLASS_MASK
        name = None
        if flags & 0x01:
            if len(payload) < off + name_len:
                raise CodecError("INTRO name truncated")
            name = payload[off:off + name_len].decode("utf-8", "replace")
        off += name_len
        lat = lon = None
        if flags & 0x02:
            if len(payload) < off + 4:
                raise CodecError("INTRO position truncated")
            dlat, dlon = struct.unpack_from("<hh", payload, off)
            off += 4
            lat, lon = _position_from_deltas(
                Intro(center_lat=center_lat, center_lon=center_lon,
                      span_m=float(wire_span)), dlat, dlon)  # noqa: E501
        intro.entries.append(IntroEntry(prefix=prefix, name=name,
                                        lat=lat, lon=lon,
                                        node_class=node_class))
    return intro


# --------------------------------------------------------------------------
# LAYOUT (0x5305)
#
# v1.6 (Brett, 2026-09-25): the section grid is no longer square -
# `grid` is the ACROSS count and a `rows` byte (down count) rides at
# the END of the body. A packet WITHOUT it is legacy square
# (grid x grid). Old decoders skip it happily (they never looked at
# trailing bytes), so one wire serves both.
# --------------------------------------------------------------------------

@dataclass
class Layout:
    seq: int
    grid: int            # sections ACROSS (columns)
    center_lat: float
    center_lon: float
    span_m: int
    origin: int = 0
    name: str = ""
    rows: int = 0        # sections DOWN; 0 = legacy square (grid x grid)


def encode_layout(l: Layout) -> bytes:
    if not 2 <= l.grid <= 5:
        raise CodecError(f"grid out of range: {l.grid}")
    rows = l.rows if l.rows > 0 else l.grid
    if not 2 <= rows <= 5:
        raise CodecError(f"rows out of range: {rows}")
    name_bytes = l.name.encode("utf-8")[:MAX_NAME]
    body = pack_header(l.seq, l.origin)
    body += struct.pack("<B", l.grid)
    body += struct.pack("<ii", round(l.center_lat * 1e6),
                        round(l.center_lon * 1e6))
    body += struct.pack("<H", _u16(l.span_m, "span_m"))
    body += struct.pack("<B", len(name_bytes))
    body += name_bytes
    body += struct.pack("<B", rows)  # v1.6: AFTER the name (legacy-safe)
    return data_type_bytes(TYPE_LAYOUT, body)


def decode_layout(payload: bytes) -> Layout:
    header, off = unpack_header(payload)
    if len(payload) < off + 8:
        raise CodecError("LAYOUT too short")
    grid = payload[off]
    off += 1
    lat_e6, lon_e6 = struct.unpack_from("<ii", payload, off)
    off += 8
    span_m = struct.unpack_from("<H", payload, off)[0]
    off += 2
    if len(payload) < off + 1:
        raise CodecError("LAYOUT name length missing")
    name_len = payload[off]
    off += 1
    if len(payload) < off + name_len:
        raise CodecError("LAYOUT name truncated")
    name = payload[off:off + name_len].decode("utf-8", "replace")
    off += name_len
    # v1.6 trailing rows byte; absent = legacy square (grid x grid).
    rows = grid
    if len(payload) > off:
        rows = payload[off]
        if not 2 <= rows <= 5:
            raise CodecError(f"LAYOUT rows out of range: {rows}")
    return Layout(seq=header.seq, grid=grid, center_lat=lat_e6 / 1e6,
                  center_lon=lon_e6 / 1e6, span_m=span_m,
                  origin=header.origin, name=name, rows=rows)


# --------------------------------------------------------------------------
# SNAP (0x5306)
# --------------------------------------------------------------------------

@dataclass
class Snap:
    seq: int
    snap_id: int
    part: int
    parts: int
    body: bytes
    origin: int = 0


def encode_snap(s: Snap) -> bytes:
    if len(s.body) > 255:
        raise CodecError(f"SNAP body too long: {len(s.body)}")
    body = pack_header(s.seq, s.origin)
    body += struct.pack("<BBB", _u8(s.snap_id, "snap_id"),
                        _u8(s.part, "part"), _u8(s.parts, "parts"))
    body += s.body
    return data_type_bytes(TYPE_SNAP, body)


def decode_snap(payload: bytes) -> Snap:
    header, off = unpack_header(payload)
    if len(payload) < off + 3:
        raise CodecError("SNAP too short")
    snap_id, part, parts = struct.unpack_from("<BBB", payload, off)
    off += 3
    return Snap(seq=header.seq, snap_id=snap_id, part=part, parts=parts,
                origin=header.origin, body=bytes(payload[off:]))


# --------------------------------------------------------------------------
# REFRESH_REQ (0x5311) - client -> host
# --------------------------------------------------------------------------

@dataclass
class RefreshReq:
    seq: int
    kind: int          # 1 = section, 2 = route
    target: int        # section_id or route_id
    nonce: int
    origin: int = 0    # client's own 2-byte id (v1.1)
    host: int = REFRESH_HOST_ANY  # preferred origin, 0 = owner decides
    # v1.3: the window the client wants, in km (20/40/60). 0 = host
    # decides = the whole 60x60 home box (today's behavior, and what
    # every pre-v1.3 encoder means when it omits the field).
    span_km: int = REFRESH_SPAN_HOST_DECIDES
    # v1.6 (vectored sync): the client's change-counter marker; the
    # answer ships full records only for nodes changed after it.
    # 0 = "not vectored" = the full roster (today's behavior).
    sync_marker: int = 0


def encode_refresh_req(r: RefreshReq) -> bytes:
    if r.kind not in (REFRESH_KIND_SECTION, REFRESH_KIND_ROUTE):
        raise CodecError(f"refresh kind invalid: {r.kind}")
    body = pack_header(r.seq, r.origin, version=PROTO_VERSION_REFRESH)
    body += struct.pack("<BHHH", r.kind, _u16(r.target, "target"),
                        _u16(r.host, "host"), _u16(r.nonce, "nonce"))
    # v1.3 (0x04): + span_km(2 LE). The version byte in the header is
    # what tells an old decoder "this body is longer than you think" -
    # and a strict old decoder REJECTS it loudly rather than misreads
    # (the same rule that guards unknown versions against us).
    body += struct.pack("<H", _u16(r.span_km, "span_km"))
    # v1.6 (0x06): + sync_marker(2 LE) - 0 = not vectored.
    body += struct.pack("<H", _u16(r.sync_marker, "sync_marker"))
    return data_type_bytes(TYPE_REFRESH_REQ, body)


def decode_refresh_req(payload: bytes) -> RefreshReq:
    header, off = unpack_header(payload)
    if header.version >= 0x06:
        # v1.6 body: kind(1) target(2) host(2) nonce(2) span_km(2)
        #             sync_marker(2)
        if len(payload) < off + 11:
            raise CodecError("REFRESH_REQ too short")
        kind, target, host = struct.unpack_from("<BHH", payload, off)
        nonce, span_km = struct.unpack_from("<HH", payload, off + 5)
        sync_marker = struct.unpack_from("<H", payload, off + 9)[0]
    elif header.version >= 0x04:
        # v1.3 body: kind(1) target(2) host(2) nonce(2) span_km(2)
        if len(payload) < off + 9:
            raise CodecError("REFRESH_REQ too short")
        kind, target, host = struct.unpack_from("<BHH", payload, off)
        nonce, span_km = struct.unpack_from("<HH", payload, off + 5)
        sync_marker = 0
    elif header.version >= 0x02:
        # v1.1 body: kind(1) target(2) host(2) nonce(2), no span_km
        if len(payload) < off + 7:
            raise CodecError("REFRESH_REQ too short")
        kind, target, host = struct.unpack_from("<BHH", payload, off)
        nonce = struct.unpack_from("<H", payload, off + 5)[0]
        span_km = REFRESH_SPAN_HOST_DECIDES
        sync_marker = 0
    else:
        # v1 body: kind(1) target(2) nonce(2), no host field
        if len(payload) < off + 5:
            raise CodecError("REFRESH_REQ too short")
        kind, target, nonce = struct.unpack_from("<BHH", payload, off)
        host = REFRESH_HOST_ANY
        span_km = REFRESH_SPAN_HOST_DECIDES
        sync_marker = 0
    return RefreshReq(seq=header.seq, kind=kind, target=target,
                      nonce=nonce, origin=header.origin, host=host,
                      span_km=span_km, sync_marker=sync_marker)


# --------------------------------------------------------------------------
# GONE (0x5312) - vectored sync deletion notice (v1.6)
# --------------------------------------------------------------------------

@dataclass
class Gone:
    seq: int
    origin: int = 0
    prefixes: List[int] = field(default_factory=list)  # 1 byte each


def encode_gone(*, seq: int, origin: int = 0,
                prefixes: List[int]) -> bytes:
    if len(prefixes) > MAX_GONE_PER_PACKET:
        raise CodecError(f"too many gone prefixes: {len(prefixes)} "
                         f"> {MAX_GONE_PER_PACKET}")
    body = pack_header(seq, origin, version=PROTO_VERSION_GONE)
    body += struct.pack("<B", len(prefixes))
    for pfx in prefixes:
        body += struct.pack("<B", _u8(pfx, "gone prefix"))
    return data_type_bytes(TYPE_GONE, body)


def decode_gone(payload: bytes) -> Gone:
    header, off = unpack_header(payload)
    if len(payload) < off + 1:
        raise CodecError("GONE too short")
    n = payload[off]
    off += 1
    if len(payload) < off + n:
        raise CodecError("GONE prefixes truncated")
    prefixes = [payload[off + i] for i in range(n)]
    return Gone(seq=header.seq, origin=header.origin, prefixes=prefixes)


# --------------------------------------------------------------------------
# Generic decode + helpers
# --------------------------------------------------------------------------

def peek_data_type(payload: bytes) -> int:
    """The data_type of a full GRP_DATA plaintext (before decoding)."""
    if len(payload) < 3:
        raise CodecError("payload too short for data_type")
    return struct.unpack_from("<H", payload, 0)[0]


def decode_any(payload: bytes) -> object:
    """Decode any scope packet by its data_type. A v1.5+ INTRO decodes
    by its OWN carried span (no caller knowledge needed)."""
    data_type = peek_data_type(payload)
    return decode_body(data_type, payload[3:])


def decode_body(data_type: int, body: bytes) -> object:
    """Decode a scope BODY whose 3-byte type/len envelope is already
    stripped (what the companion delivers in CHANNEL_DATA_RECV: the
    radio decrypts and removes its own framing before queueing -
    meshcore reader.py sets payload = data_len bytes; openhop_core
    companion_base._handle_group_data_packet queues blob =
    plaintext[3:3+data_len])."""
    if data_type == TYPE_PULSE:
        return decode_pulse(body)
    if data_type == TYPE_SECT_SUM:
        return decode_sect_sum(body)
    if data_type == TYPE_ROUTE:
        return decode_route(body)
    if data_type == TYPE_INTRO:
        return decode_intro(body)
    if data_type == TYPE_LAYOUT:
        return decode_layout(body)
    if data_type == TYPE_SNAP:
        return decode_snap(body)
    if data_type == TYPE_REFRESH_REQ:
        return decode_refresh_req(body)
    if data_type == TYPE_GONE:
        return decode_gone(body)
    raise CodecError(f"unknown data_type {data_type:#06x}")


# --------------------------------------------------------------------------
# Range guards
# --------------------------------------------------------------------------

def _u8(value: int, what: str) -> int:
    value = int(value)
    if not 0 <= value <= 0xFF:
        raise CodecError(f"{what} out of range: {value}")
    return value


def _u16(value: int, what: str) -> int:
    value = int(value)
    if not 0 <= value <= 0xFFFF:
        raise CodecError(f"{what} out of range: {value}")
    return value
